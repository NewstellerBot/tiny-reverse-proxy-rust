fn parse_string_array(raw: &str) -> Vec<String> {
    serde_json::from_str::<Vec<String>>(raw).unwrap_or_else(|_| {
        raw.trim()
            .trim_start_matches('[')
            .trim_end_matches(']')
            .split(',')
            .filter_map(|entry| {
                let trimmed = entry.trim().trim_matches('"');
                (!trimmed.is_empty()).then(|| trimmed.to_string())
            })
            .collect()
    })
}

fn resolve_provider_api_key_env(env_var: &str) -> Result<String, String> {
    let trimmed = env_var.trim();
    if trimmed.is_empty() {
        return Err("api_key_env must not be empty".to_string());
    }
    std::env::var(trimmed)
        .map_err(|_| format!("provider api_key_env '{trimmed}' is not set in the environment"))
}

fn parse_provider_routing_metadata_json(
    raw: Option<&str>,
) -> Result<ProviderRoutingMetadataConfig, String> {
    let Some(raw) = raw else {
        return Ok(ProviderRoutingMetadataConfig::default());
    };
    let value: Value = serde_json::from_str(raw)
        .map_err(|error| format!("routing_metadata must be valid JSON: {error}"))?;
    let object = value
        .as_object()
        .ok_or_else(|| "routing_metadata must be a JSON object".to_string())?;
    let data_collection = object
        .get("data_collection")
        .and_then(Value::as_str)
        .map(|value| {
            ProviderDataCollectionMode::parse(value).ok_or_else(|| {
                format!(
                    "routing_metadata.data_collection must be one of allow, deny (got '{value}')"
                )
            })
        })
        .transpose()?;
    let zdr = object.get("zdr").and_then(Value::as_bool).unwrap_or(false);
    let distillable_text = object
        .get("distillable_text")
        .and_then(Value::as_bool)
        .unwrap_or(false);
    let quantizations = object
        .get("quantizations")
        .map(|value| {
            value
                .as_array()
                .ok_or_else(|| {
                    "routing_metadata.quantizations must be an array of strings".to_string()
                })?
                .iter()
                .map(|entry| {
                    entry.as_str().map(str::to_string).ok_or_else(|| {
                        "routing_metadata.quantizations entries must be strings".to_string()
                    })
                })
                .collect::<Result<Vec<_>, _>>()
        })
        .transpose()?
        .unwrap_or_default();
    let supported_parameter_families = object
        .get("supported_parameter_families")
        .map(|value| {
            value
                .as_array()
                .ok_or_else(|| {
                    "routing_metadata.supported_parameter_families must be an array of strings"
                        .to_string()
                })?
                .iter()
                .map(|entry| {
                    entry.as_str().map(str::to_string).ok_or_else(|| {
                        "routing_metadata.supported_parameter_families entries must be strings"
                            .to_string()
                    })
                })
                .collect::<Result<Vec<_>, _>>()
        })
        .transpose()?
        .unwrap_or_default();
    Ok(ProviderRoutingMetadataConfig {
        data_collection,
        zdr,
        distillable_text,
        quantizations,
        supported_parameter_families,
    })
}

pub(crate) fn resolve_managed_provider_record(
    record: &ManagedProviderRecord,
    base: Option<&ProviderKeyConfig>,
) -> Result<ProviderKeyConfig, String> {
    let api_key = match record.api_key_env.as_deref() {
        Some(env_var) => resolve_provider_api_key_env(env_var)?,
        None => base
            .map(|provider| provider.api_key.clone())
            .ok_or_else(|| format!("provider '{}' must set api_key_env", record.name))?,
    };
    let base_url = record
        .base_url
        .clone()
        .or_else(|| base.map(|provider| provider.base_url.clone()))
        .ok_or_else(|| format!("provider '{}' must set base_url", record.name))?;
    let models = record
        .models_json
        .as_deref()
        .map(|raw| {
            serde_json::from_str::<Vec<String>>(raw)
                .map_err(|error| format!("models must be a JSON array of strings: {error}"))
        })
        .transpose()?
        .or_else(|| base.map(|provider| provider.models.clone()))
        .ok_or_else(|| format!("provider '{}' must set models", record.name))?;
    if models.is_empty() {
        return Err(format!(
            "provider '{}' must have at least one model",
            record.name
        ));
    }
    let api_key_header = record
        .api_key_header
        .clone()
        .or_else(|| base.map(|provider| provider.api_key_header.clone()))
        .unwrap_or_else(|| "authorization".to_string());
    let timeout_secs = record
        .timeout_secs
        .or_else(|| base.and_then(|provider| provider.timeout_secs));
    let routing_metadata = if record.routing_metadata_json.is_some() {
        parse_provider_routing_metadata_json(record.routing_metadata_json.as_deref())?
    } else {
        base.map(|provider| provider.routing_metadata.clone())
            .unwrap_or_default()
    };
    let explicit_surfaces = record
        .surfaces_json
        .as_deref()
        .map(|raw| {
            serde_json::from_str::<ProviderSurfaceCatalog>(raw)
                .map_err(|error| format!("invalid surfaces_json: {error}"))
        })
        .transpose()?;
    let surfaces = explicit_surfaces
        .or_else(|| base.map(|provider| provider.surfaces().clone()))
        .unwrap_or_default();
    let family = if let Some(raw_family) = record.family.as_deref() {
        Some(
            ProviderFamily::parse(raw_family)
                .ok_or_else(|| format!("invalid family '{raw_family}'"))?,
        )
    } else {
        base.map(|provider| provider.family_kind())
    };
    let family = ProviderFamilyConfig::from_optional_parts(record.name.as_str(), family, surfaces)?;
    let mut provider = ProviderKeyConfig::new(
        ProviderCommonConfig {
            name: record.name.clone(),
            api_key,
            base_url,
            models,
            api_key_header,
            timeout_secs,
            routing_metadata,
        },
        family,
    );
    provider.refresh_derived_semantics();
    Ok(provider)
}

