    fn rebuild_provider_indexes(&self) {
        self.providers.clear();
        self.model_to_provider.clear();

        let mut effective = self
            .base_providers
            .iter()
            .map(|(name, provider)| (name.clone(), provider.clone()))
            .collect::<HashMap<_, _>>();

        let mut overlays = self
            .managed_providers
            .iter()
            .map(|entry| entry.value().clone())
            .collect::<Vec<_>>();
        overlays.sort_by(|left, right| left.name.cmp(&right.name));

        for record in overlays {
            let base = self.base_providers.get(&record.name);
            if !record.enabled {
                effective.remove(record.name.as_str());
                continue;
            }
            match resolve_managed_provider_record(&record, base) {
                Ok(provider) => {
                    effective.insert(record.name.clone(), provider);
                }
                Err(error) => {
                    tracing::warn!(
                        provider = %record.name,
                        error = %error,
                        "virtual_keys: skipping invalid managed provider record"
                    );
                    effective.remove(record.name.as_str());
                }
            }
        }

        let mut ordered_names = Vec::new();
        for name in self.base_provider_order.iter() {
            if effective.contains_key(name) {
                ordered_names.push(name.clone());
            }
        }

        let mut dynamic_names = effective
            .keys()
            .filter(|name| !self.base_providers.contains_key(name.as_str()))
            .cloned()
            .collect::<Vec<_>>();
        dynamic_names.sort_by(|left, right| {
            let left_record = self.managed_provider_record(left);
            let right_record = self.managed_provider_record(right);
            match (left_record, right_record) {
                (Some(left_record), Some(right_record)) => left_record
                    .created_at
                    .cmp(&right_record.created_at)
                    .then_with(|| left.cmp(right)),
                _ => left.cmp(right),
            }
        });
        ordered_names.extend(dynamic_names);

        *self
            .provider_order
            .write()
            .unwrap_or_else(|poison| poison.into_inner()) = ordered_names.clone();

        for name in ordered_names {
            let Some(provider) = effective.remove(name.as_str()) else {
                continue;
            };
            for model in &provider.models {
                self.model_to_provider
                    .entry(model.clone())
                    .or_default()
                    .push(provider.name.clone());
            }
            self.providers.insert(provider.name.clone(), provider);
        }
    }

    pub fn static_provider_configs(&self) -> Vec<ProviderKeyConfig> {
        self.base_provider_order
            .iter()
            .filter_map(|name| self.base_providers.get(name).cloned())
            .collect()
    }

    pub fn managed_provider_records(&self) -> Vec<ManagedProviderRecord> {
        let mut records = self
            .managed_providers
            .iter()
            .map(|entry| entry.value().clone())
            .collect::<Vec<_>>();
        records.sort_by(|left, right| left.name.cmp(&right.name));
        records
    }

    pub fn managed_provider_record(&self, name: &str) -> Option<ManagedProviderRecord> {
        self.managed_providers
            .get(name)
            .map(|entry| entry.value().clone())
    }

    pub fn effective_provider_config(&self, name: &str) -> Option<ProviderKeyConfig> {
        self.providers.get(name).map(|entry| entry.value().clone())
    }

    pub fn resolve_provider_preview(
        &self,
        name: &str,
    ) -> Result<Option<ProviderKeyConfig>, String> {
        let base = self.base_providers.get(name);
        let managed = self.managed_provider_record(name);
        match (managed.as_ref(), base) {
            (Some(record), base) => resolve_managed_provider_record(record, base).map(Some),
            (None, Some(provider)) => Ok(Some(provider.clone())),
            (None, None) => Ok(None),
        }
    }

    pub async fn upsert_managed_provider(
        &self,
        record: ManagedProviderRecord,
    ) -> Result<(), Box<dyn std::error::Error>> {
        let has_base = self.base_providers.contains_key(&record.name);
        let has_existing_managed = self.managed_providers.contains_key(&record.name);
        if !record.enabled && !has_base && !has_existing_managed {
            return Err(format!(
                "cannot disable unknown provider '{}'; create it first or target an existing static provider",
                record.name
            )
            .into());
        }
        if record.enabled {
            resolve_managed_provider_record(&record, self.base_providers.get(&record.name))?;
        }

        if let Some(store) = &self.store {
            store.upsert_managed_provider(&record).await?;
        }
        self.managed_providers.insert(record.name.clone(), record);
        self.rebuild_provider_indexes();
        Ok(())
    }

    pub async fn delete_managed_provider(
        &self,
        name: &str,
    ) -> Result<bool, Box<dyn std::error::Error>> {
        let deleted = if let Some(store) = &self.store {
            store.delete_managed_provider(name).await?
        } else {
            self.managed_providers.contains_key(name)
        };
        self.managed_providers.remove(name);
        self.rebuild_provider_indexes();
        Ok(deleted)
    }

    /// Load all virtual keys from the persistent store into the DashMap cache.
    pub async fn load_from_store(&self) -> Result<(), Box<dyn std::error::Error>> {
        let store = match &self.store {
            Some(s) => s,
            None => return Ok(()),
        };

        self.managed_providers.clear();
        for record in store.get_managed_providers().await? {
            self.managed_providers.insert(record.name.clone(), record);
        }
        self.rebuild_provider_indexes();

        let records = store.get_all_virtual_keys().await?;
        for record in records {
            if record.project_id.is_empty() {
                return Err("virtual key is missing project_id".into());
            }
            self.keys
                .insert(record.key_hash.clone(), CachedKey { record });
        }

        tracing::info!("virtual_keys: loaded {} keys from store", self.keys.len());
        Ok(())
    }

    /// Generate a new virtual key: returns (plaintext_key, key_hash).
    pub fn generate_key() -> (String, String) {
        use rand::Rng;
        let mut rng = rand::thread_rng();
        let mut random_bytes = [0u8; 32];
        rng.fill(&mut random_bytes);
        let random_hex = hex::encode(random_bytes);
        let plaintext = format!("{}{}", KEY_PREFIX, random_hex);
        let hash = hash_key(&plaintext);
        (plaintext, hash)
    }

