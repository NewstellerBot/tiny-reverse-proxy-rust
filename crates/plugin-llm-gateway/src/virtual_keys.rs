    pub fn get_key_by_prefix(
        &self,
        prefix: &str,
    ) -> Result<Option<VirtualKeyRecord>, VirtualKeyLookupError> {
        let full_hash = match self.find_full_hash(prefix)? {
            Some(hash) => hash,
            None => return Ok(None),
        };
        Ok(self
            .keys
            .get(&full_hash)
            .map(|entry| entry.value().record.clone()))
    }

