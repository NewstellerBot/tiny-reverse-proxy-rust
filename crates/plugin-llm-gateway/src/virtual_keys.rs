    fn collect_from_json(path: &str, request_json: &serde_json::Value, requirements: &mut Self) {
        if request_json.get("reasoning").is_some() || request_json.get("thinking").is_some() {
            requirements.reasoning = true;
        }
        Self::collect_structured_output_from_request(path, request_json, requirements);
        Self::collect_from_value(request_json, requirements);
    }

    fn collect_structured_output_from_request(
        path: &str,
        request_json: &serde_json::Value,
        requirements: &mut Self,
    ) {
        let format_type =
            if path == "/v1/chat/completions" || path.starts_with("/v1/chat/completions/") {
                request_json
                    .get("response_format")
                    .and_then(|value| value.get("type"))
                    .and_then(serde_json::Value::as_str)
            } else if path == "/v1/responses" || path.starts_with("/v1/responses/") {
                request_json
                    .pointer("/text/format/type")
                    .and_then(serde_json::Value::as_str)
            } else {
                None
            };

        match format_type {
            Some("json_object") => requirements.structured_output_json_mode = true,
            Some("json_schema") => requirements.structured_output_json_schema = true,
            _ => {}
        }
    }

    fn collect_from_value(value: &serde_json::Value, requirements: &mut Self) {
        match value {
            serde_json::Value::Object(map) => {
                if modalitites_include_audio(map.get("modalities"))
                    || modalitites_include_audio(map.get("output_modalities"))
                {
                    requirements.audio_output = true;
                }
                if map.contains_key("input_audio") {
                    requirements.audio_input = true;
                }
                if let Some(kind) = map.get("type").and_then(|value| value.as_str()) {
                    match kind {
                        "input_image" | "image_url" => {
                            requirements.image_input = true;
                        }
                        "image"
                            if map.contains_key("image_url")
                                || map.contains_key("url")
                                || map.contains_key("source")
                                || map.contains_key("data") =>
                        {
                            requirements.image_input = true;
                        }
                        "input_audio" => {
                            requirements.audio_input = true;
                        }
                        "audio"
                            if map.contains_key("input_audio")
                                || map.contains_key("url")
                                || map.contains_key("source")
                                || map.contains_key("data") =>
                        {
                            requirements.audio_input = true;
                        }
                        _ => {}
                    }
                }
                for value in map.values() {
                    Self::collect_from_value(value, requirements);
                }
            }
            serde_json::Value::Array(values) => {
                for value in values {
                    Self::collect_from_value(value, requirements);
                }
            }
            _ => {}
        }
    }

    fn supports(&self, provider: &ProviderKeyConfig) -> bool {
        self.first_missing_for(provider).is_none()
    }

    fn first_missing_for(&self, provider: &ProviderKeyConfig) -> Option<ProviderExtraCapability> {
        self.required_capabilities()
            .into_iter()
            .find(|&capability| !provider.supports_capability(capability))
    }

    fn first_required_capability(&self) -> Option<ProviderExtraCapability> {
        self.required_capabilities().into_iter().next()
    }

