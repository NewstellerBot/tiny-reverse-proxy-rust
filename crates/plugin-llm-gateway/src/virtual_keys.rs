    pub fn new_with_governance(
        provider_configs: &[ProviderKeyConfig],
        model_aliases: &[ModelAliasConfig],
        store: Option<Arc<Store>>,
        governance: Arc<GovernanceState>,
        allow_direct_provider_keys: bool,
    ) -> Self {
        let normalized_provider_configs = provider_configs
            .iter()
            .cloned()
            .map(|mut provider| {
                provider.refresh_derived_semantics();
                provider
            })
            .collect::<Vec<_>>();
        let base_provider_order = Arc::new(
            normalized_provider_configs
                .iter()
                .map(|provider| provider.name.clone())
                .collect::<Vec<_>>(),
        );
        let base_providers = Arc::new(
            normalized_provider_configs
                .iter()
                .map(|provider| (provider.name.clone(), provider.clone()))
                .collect::<HashMap<_, _>>(),
        );
        let providers = Arc::new(DashMap::new());
        let provider_order = Arc::new(RwLock::new(Vec::new()));
        let managed_providers = Arc::new(DashMap::new());
        let model_to_provider = Arc::new(DashMap::new());
        let aliases = Arc::new(DashMap::new());

        for alias in model_aliases {
            aliases.insert(alias.alias.clone(), alias.model.clone());
        }

        let instance = Self {
            keys: Arc::new(DashMap::new()),
            base_providers,
            base_provider_order,
            managed_providers,
            providers,
            provider_order,
            model_to_provider,
            model_aliases: aliases,
            store,
            governance,
            allow_direct_provider_keys,
            metrics: None,
            prompt_cache_anthropic_default_scope: Arc::new(RwLock::new(PromptCacheScope::Auto)),
            prompt_cache_routing_memory: Arc::new(RwLock::new(None)),
            semantic_cache_handle: Arc::new(RwLock::new(None)),
            file_provider_routes: Arc::new(DashMap::new()),
            batch_provider_routes: Arc::new(DashMap::new()),
        };
        instance.rebuild_provider_indexes();
        instance
    }

