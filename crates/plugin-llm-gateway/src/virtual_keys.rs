pub fn normalize_tool_approval_mode_value(
    raw_mode: Option<&str>,
    allowed_tools_json: Option<&str>,
) -> Result<Option<String>, String> {
    let normalized = raw_mode
        .map(str::trim)
        .filter(|value| !value.is_empty())
        .map(|value| value.to_ascii_lowercase());
    match normalized.as_deref() {
        Some("allow_all") | Some("deny_all") | Some("allow_list") => Ok(normalized),
        Some(other) => Err(format!(
            "tool_approval_mode must be one of allow_all, deny_all, allow_list (got '{other}')"
        )),
        None if allowed_tools_json.is_some() => {
            Ok(Some(ToolApprovalMode::AllowList.as_str().into()))
        }
        None => Ok(None),
    }
}

pub fn effective_tool_approval_policy(
    key_mode: Option<&str>,
    key_allowed_tools: Option<&str>,
    project_mode: Option<&str>,
    project_allowed_tools: Option<&str>,
) -> Result<(ToolApprovalMode, Option<Vec<String>>, &'static str), String> {
    let key_mode = normalize_tool_approval_mode_value(key_mode, key_allowed_tools)?;
    let project_mode = normalize_tool_approval_mode_value(project_mode, project_allowed_tools)?;

    if key_mode.is_some() || key_allowed_tools.is_some() {
        return Ok((
            parse_tool_approval_mode(key_mode.as_deref(), key_allowed_tools),
            key_allowed_tools.map(parse_string_array),
            "virtual_key",
        ));
    }
    if project_mode.is_some() || project_allowed_tools.is_some() {
        return Ok((
            parse_tool_approval_mode(project_mode.as_deref(), project_allowed_tools),
            project_allowed_tools.map(parse_string_array),
            "project_policy",
        ));
    }

    Ok((ToolApprovalMode::AllowAll, None, "default"))
}

fn parse_tool_approval_mode(
    normalized_mode: Option<&str>,
    allowed_tools_json: Option<&str>,
) -> ToolApprovalMode {
    match normalized_mode {
        Some("deny_all") => ToolApprovalMode::DenyAll,
        Some("allow_list") => ToolApprovalMode::AllowList,
        Some("allow_all") => ToolApprovalMode::AllowAll,
        _ if allowed_tools_json.is_some() => ToolApprovalMode::AllowList,
        _ => ToolApprovalMode::AllowAll,
    }
}

