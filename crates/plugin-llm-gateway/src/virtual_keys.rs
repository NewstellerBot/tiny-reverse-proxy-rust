    fn request_policy_supported_request(method: &hyper::Method, path: &str) -> bool {
        (matches!(
            path,
            "/v1/chat/completions"
                | "/v1/responses"
                | "/v1/embeddings"
                | "/v1/images/generations"
                | "/v1/audio/speech"
        ) || path.starts_with("/v1/chat/completions/")
            || path.starts_with("/v1/responses/")
            || path.starts_with("/v1/embeddings/")
            || path.starts_with("/v1/images/generations/")
            || path.starts_with("/v1/audio/speech/"))
            && *method == hyper::Method::POST
            || (*method == hyper::Method::POST && path == "/v1/batches")
    }

    fn extract_request_provider_policy(
        &self,
        ctx: &mut RequestContext,
        request_method: &hyper::Method,
        request_path: &str,
    ) -> Result<
        Option<RequestProviderPolicy>,
        Response<http_body_util::combinators::BoxBody<Bytes, hyper::Error>>,
    > {
        if matches!(
            ImageRequestOperation::from_path(request_path),
            Some(ImageRequestOperation::Edits | ImageRequestOperation::Variations)
        ) && body_contains_multipart_field(ctx.body.as_deref(), "provider")
        {
            return Err(json_error_response(
                StatusCode::BAD_REQUEST,
                "provider request policy is only supported on JSON image generation requests, not multipart image edits or variations",
                "invalid_request_error",
                "provider_policy_unsupported",
            ));
        }
        if matches!(
            AudioRequestOperation::from_path(request_path),
            Some(AudioRequestOperation::Transcriptions | AudioRequestOperation::Translations)
        ) && body_contains_multipart_field(ctx.body.as_deref(), "provider")
        {
            return Err(json_error_response(
                StatusCode::BAD_REQUEST,
                "provider request policy is only supported on JSON audio speech requests, not multipart audio transcription or translation requests",
                "invalid_request_error",
                "provider_policy_unsupported",
            ));
        }
        if matches!(
            FileRequestOperation::from_request(request_method, request_path),
            Some(FileRequestOperation::Create)
        ) && body_contains_multipart_field(ctx.body.as_deref(), "provider")
        {
            return Err(json_error_response(
                StatusCode::BAD_REQUEST,
                "provider request policy is not supported on multipart file upload requests",
                "invalid_request_error",
                "provider_policy_unsupported",
            ));
        }
        let Some(request_json) = cached_request_json_mut(ctx) else {
            return Ok(None);
        };
        let Some(provider_value) = request_json.get("provider").cloned() else {
            return Ok(None);
        };
        if !Self::request_policy_supported_request(request_method, request_path) {
            return Err(json_error_response(
                StatusCode::BAD_REQUEST,
                "provider request policy is only supported on POST /v1/chat/completions, POST /v1/responses, POST /v1/embeddings, POST /v1/images/generations, POST /v1/audio/speech, and POST /v1/batches",
                "invalid_request_error",
                "provider_policy_unsupported",
            ));
        }
        let policy: RequestProviderPolicy =
            serde_json::from_value(provider_value).map_err(|error| {
                json_error_response(
                    StatusCode::BAD_REQUEST,
                    &format!("provider must use supported snake_case fields: {error}"),
                    "invalid_request_error",
                    "invalid_provider_policy",
                )
            })?;
        if let Err(error) = policy.validate_supported_shape() {
            return Err(json_error_response(
                StatusCode::BAD_REQUEST,
                &error,
                "invalid_request_error",
                "provider_policy_unsupported",
            ));
        }
        if let Err(error) = policy.validate_provider_names(&self.configured_provider_names()) {
            return Err(json_error_response(
                StatusCode::BAD_REQUEST,
                &error,
                "invalid_request_error",
                "invalid_provider_policy",
            ));
        }
        request_json
            .as_object_mut()
            .map(|value| value.remove("provider"));
        if let Err(error) = sync_cached_request_json_body(ctx) {
            return Err(json_error_response(
                StatusCode::BAD_REQUEST,
                &error,
                "invalid_request_error",
                "invalid_request_json",
            ));
        }
        Ok(Some(policy))
    }

    fn request_parameter_requirements(
        request_json: Option<&Value>,
        prompt_cache_hint: Option<PromptCacheRoutingHint>,
    ) -> RequestParameterRequirements {
        let mut requirements = RequestParameterRequirements::default();
        if let Some(request_json) = request_json {
            requirements.tools = request_json.get("tools").is_some()
                || request_json.get("tool_choice").is_some()
                || request_json.get("trp_tools").is_some();
        }
        requirements.prompt_cache_controls =
            prompt_cache_hint.map(|hint| hint.enabled).unwrap_or(false);
        requirements
    }

    fn parse_float_map(value: Option<&str>) -> HashMap<String, f64> {
        value
            .and_then(|raw| serde_json::from_str::<HashMap<String, f64>>(raw).ok())
            .unwrap_or_default()
    }

    fn filter_providers_for_request_policy(
        &self,
        mut providers: Vec<ProviderKeyConfig>,
        policy: &RequestProviderPolicy,
        parameter_requirements: &RequestParameterRequirements,
        project_policy: Option<&ProjectPolicyRecord>,
    ) -> Result<Vec<ProviderKeyConfig>, String> {
        if let Some(only) = policy.only.as_ref() {
            let only: HashSet<&str> = only.iter().map(String::as_str).collect();
            providers.retain(|provider| only.contains(provider.name.as_str()));
        }
        if let Some(ignore) = policy.ignore.as_ref() {
            let ignore: HashSet<&str> = ignore.iter().map(String::as_str).collect();
            providers.retain(|provider| !ignore.contains(provider.name.as_str()));
        }
        if let Some(data_collection) = policy.data_collection_mode() {
            providers.retain(|provider| {
                provider.routing_metadata.data_collection.as_ref() == Some(&data_collection)
            });
        }
        if policy.zdr.unwrap_or(false) {
            providers.retain(|provider| provider.routing_metadata.zdr);
        }
        if policy.enforce_distillable_text.unwrap_or(false) {
            providers.retain(|provider| provider.routing_metadata.distillable_text);
        }
        if let Some(quantizations) = policy.quantizations.as_ref() {
            let requested: HashSet<&str> = quantizations.iter().map(String::as_str).collect();
            providers.retain(|provider| {
                !provider.routing_metadata.quantizations.is_empty()
                    && provider
                        .routing_metadata
                        .quantizations
                        .iter()
                        .any(|value| requested.contains(value.as_str()))
            });
        }
        if policy.require_parameters() {
            providers.retain(|provider| {
                let supported_families: HashSet<&str> = provider
                    .routing_metadata
                    .supported_parameter_families
                    .iter()
                    .map(String::as_str)
                    .collect();
                let tools_supported = !parameter_requirements.tools
                    || provider.surfaces().tools.is_some()
                    || supported_families.contains("tools");
                let prompt_cache_supported = !parameter_requirements.prompt_cache_controls
                    || provider
                        .supports_capability(ProviderExtraCapability::PromptCacheRequestControls)
                    || provider.supports_capability(ProviderExtraCapability::PromptCacheOpenAi)
                    || provider.supports_capability(ProviderExtraCapability::PromptCacheAnthropic)
                    || supported_families.contains("prompt_cache_controls");
                tools_supported && prompt_cache_supported
            });
        }
        if let Some(max_price) = policy.max_price.as_ref() {
            let provider_input_costs = Self::parse_float_map(
                project_policy.and_then(|policy| policy.provider_input_costs.as_deref()),
            );
            let provider_output_costs = Self::parse_float_map(
                project_policy.and_then(|policy| policy.provider_output_costs.as_deref()),
            );
            if let Some(limit) = max_price.prompt {
                providers.retain(|provider| {
                    provider_input_costs
                        .get(provider.name.as_str())
                        .copied()
                        .map(|cost| cost <= limit)
                        .unwrap_or(false)
                });
            }
            if let Some(limit) = max_price.completion {
                providers.retain(|provider| {
                    provider_output_costs
                        .get(provider.name.as_str())
                        .copied()
                        .map(|cost| cost <= limit)
                        .unwrap_or(false)
                });
            }
        }
        if matches!(
            policy.sort_by(),
            Ok(Some(RequestProviderPolicySortBy::Price))
        ) {
            let provider_input_costs = Self::parse_float_map(
                project_policy.and_then(|policy| policy.provider_input_costs.as_deref()),
            );
            let provider_output_costs = Self::parse_float_map(
                project_policy.and_then(|policy| policy.provider_output_costs.as_deref()),
            );
            providers.retain(|provider| {
                provider_input_costs.contains_key(provider.name.as_str())
                    && provider_output_costs.contains_key(provider.name.as_str())
            });
        }
        Ok(providers)
    }

    fn apply_request_provider_policy_ordering(
        &self,
        providers: Vec<ProviderKeyConfig>,
        policy: &RequestProviderPolicy,
        governance_order: &[String],
        project_policy: Option<&ProjectPolicyRecord>,
    ) -> Result<Vec<ProviderKeyConfig>, String> {
        if let Some(order) = policy.order.as_ref() {
            return Ok(self.order_providers_with_explicit_request_order(
                providers,
                order,
                governance_order,
            ));
        }
        match policy.sort_by()? {
            Some(RequestProviderPolicySortBy::Latency) => {
                Ok(self.order_providers_by_latency(providers, governance_order))
            }
            Some(RequestProviderPolicySortBy::Price) => {
                Ok(self.order_providers_by_price(providers, governance_order, project_policy))
            }
            None => Ok(self.reorder_providers(providers, governance_order)),
        }
    }

    fn order_providers_with_explicit_request_order(
        &self,
        providers: Vec<ProviderKeyConfig>,
        request_order: &[String],
        governance_order: &[String],
    ) -> Vec<ProviderKeyConfig> {
        let request_index: HashMap<&str, usize> = request_order
            .iter()
            .enumerate()
            .map(|(index, provider)| (provider.as_str(), index))
            .collect();
        let governance_index: HashMap<&str, usize> = governance_order
            .iter()
            .enumerate()
            .map(|(index, provider)| (provider.as_str(), index))
            .collect();
        let mut providers = providers;
        providers.sort_by(|left, right| {
            request_index
                .get(left.name.as_str())
                .copied()
                .unwrap_or(10_000)
                .cmp(
                    &request_index
                        .get(right.name.as_str())
                        .copied()
                        .unwrap_or(10_000),
                )
                .then_with(|| {
                    governance_index
                        .get(left.name.as_str())
                        .copied()
                        .unwrap_or(10_000)
                        .cmp(
                            &governance_index
                                .get(right.name.as_str())
                                .copied()
                                .unwrap_or(10_000),
                        )
                })
                .then_with(|| left.name.cmp(&right.name))
        });
        providers
    }

    fn order_providers_by_latency(
        &self,
        providers: Vec<ProviderKeyConfig>,
        governance_order: &[String],
    ) -> Vec<ProviderKeyConfig> {
        let governance_index: HashMap<&str, usize> = governance_order
            .iter()
            .enumerate()
            .map(|(index, provider)| (provider.as_str(), index))
            .collect();
        let mut providers = providers;
        providers.sort_by(|left, right| {
            let left_stats = self.governance.provider_health_stats(left.name.as_str());
            let right_stats = self.governance.provider_health_stats(right.name.as_str());
            let left_latency = if left_stats.samples == 0 {
                f64::MAX / 4.0
            } else {
                left_stats.ewma_latency_ms
            };
            let right_latency = if right_stats.samples == 0 {
                f64::MAX / 4.0
            } else {
                right_stats.ewma_latency_ms
            };
            left_latency
                .partial_cmp(&right_latency)
                .unwrap_or(std::cmp::Ordering::Equal)
                .then_with(|| {
                    governance_index
                        .get(left.name.as_str())
                        .copied()
                        .unwrap_or(10_000)
                        .cmp(
                            &governance_index
                                .get(right.name.as_str())
                                .copied()
                                .unwrap_or(10_000),
                        )
                })
                .then_with(|| left.name.cmp(&right.name))
        });
        providers
    }

    fn order_providers_by_price(
        &self,
        providers: Vec<ProviderKeyConfig>,
        governance_order: &[String],
        project_policy: Option<&ProjectPolicyRecord>,
    ) -> Vec<ProviderKeyConfig> {
        let governance_index: HashMap<&str, usize> = governance_order
            .iter()
            .enumerate()
            .map(|(index, provider)| (provider.as_str(), index))
            .collect();
        let input_costs = Self::parse_float_map(
            project_policy.and_then(|policy| policy.provider_input_costs.as_deref()),
        );
        let output_costs = Self::parse_float_map(
            project_policy.and_then(|policy| policy.provider_output_costs.as_deref()),
        );
        let mut providers = providers;
        providers.sort_by(|left, right| {
            let left_price = (
                input_costs
                    .get(left.name.as_str())
                    .copied()
                    .unwrap_or(f64::MAX / 4.0),
                output_costs
                    .get(left.name.as_str())
                    .copied()
                    .unwrap_or(f64::MAX / 4.0),
            );
            let right_price = (
                input_costs
                    .get(right.name.as_str())
                    .copied()
                    .unwrap_or(f64::MAX / 4.0),
                output_costs
                    .get(right.name.as_str())
                    .copied()
                    .unwrap_or(f64::MAX / 4.0),
            );
            left_price
                .partial_cmp(&right_price)
                .unwrap_or(std::cmp::Ordering::Equal)
                .then_with(|| {
                    governance_index
                        .get(left.name.as_str())
                        .copied()
                        .unwrap_or(10_000)
                        .cmp(
                            &governance_index
                                .get(right.name.as_str())
                                .copied()
                                .unwrap_or(10_000),
                        )
                })
                .then_with(|| left.name.cmp(&right.name))
        });
        providers
    }

    /// Update fields on a virtual key.
    pub async fn update_key(
        &self,
        hash_prefix: &str,
        budget_limit: Option<Option<f64>>,
        rpm_limit: Option<Option<u32>>,
        tpm_limit: Option<Option<u32>>,
        active: Option<bool>,
        allowed_models: Option<Option<Vec<String>>>,
        expires_at: Option<Option<String>>,
    ) -> Result<bool, Box<dyn std::error::Error>> {
        self.update_key_with_timeout(
            hash_prefix,
            budget_limit,
            rpm_limit,
            tpm_limit,
            active,
            allowed_models,
            expires_at,
            None,
        )
        .await
    }

