    fn apply_image_request_protocol(
        &self,
        ctx: &mut RequestContext,
        provider: &ProviderKeyConfig,
        image_operation: ImageRequestOperation,
    ) -> Result<ImageRequestTransform, Response<BoxBody<Bytes, hyper::Error>>> {
        match provider
            .surfaces()
            .images
            .as_ref()
            .map(|surface| &surface.protocol)
        {
            None => Err(json_error_response(
                StatusCode::BAD_REQUEST,
                "The selected provider does not declare image surface support",
                "invalid_request_error",
                "provider_surface_unsupported",
            )),
            Some(proxy_core::config::ImageSurfaceProtocol::OpenAiImages) => {
                Ok(ImageRequestTransform {
                    operation: image_operation,
                    protocol: proxy_core::config::ImageSurfaceProtocol::OpenAiImages,
                })
            }
            Some(proxy_core::config::ImageSurfaceProtocol::OpenRouterChatImages) => {
                if image_operation != ImageRequestOperation::Generations {
                    return Err(json_error_response(
                        StatusCode::BAD_REQUEST,
                        "openrouter_chat_images providers only support /v1/images/generations in v1",
                        "invalid_request_error",
                        "provider_surface_unsupported",
                    ));
                }
                if let Err(error) = translate_openai_image_generation_to_openrouter(ctx) {
                    return Err(json_error_response(
                        StatusCode::BAD_REQUEST,
                        &error,
                        "invalid_request_error",
                        "provider_surface_unsupported",
                    ));
                }
                if let Err(error) = replace_request_path(ctx, image_operation.translated_path()) {
                    return Err(json_error_response(
                        StatusCode::INTERNAL_SERVER_ERROR,
                        &error,
                        "server_error",
                        "image_request_rewrite_failed",
                    ));
                }
                Ok(ImageRequestTransform {
                    operation: image_operation,
                    protocol: proxy_core::config::ImageSurfaceProtocol::OpenRouterChatImages,
                })
            }
        }
    }

