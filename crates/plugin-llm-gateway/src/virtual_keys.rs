    fn parse_provider_timeout_overrides(raw: &str) -> Option<HashMap<String, u64>> {
        let value: serde_json::Value = serde_json::from_str(raw).ok()?;
        let object = value.as_object()?;
        object
            .iter()
            .map(|(provider, value)| {
                let secs = value
                    .as_u64()
                    .or_else(|| value.as_i64().and_then(|value| u64::try_from(value).ok()))?;
                Some((provider.clone(), secs))
            })
            .collect::<Option<HashMap<_, _>>>()
    }

    fn parse_provider_limit_overrides(raw: &str) -> Option<HashMap<String, u32>> {
        let value: serde_json::Value = serde_json::from_str(raw).ok()?;
        let object = value.as_object()?;
        object
            .iter()
            .map(|(provider, value)| {
                let limit = value
                    .as_u64()
                    .or_else(|| value.as_i64().and_then(|value| u64::try_from(value).ok()))
                    .and_then(|value| u32::try_from(value).ok())?;
                Some((provider.clone(), limit))
            })
            .collect::<Option<HashMap<_, _>>>()
    }

    fn project_timeout_override(
        policy: Option<&ProjectPolicyRecord>,
        provider_name: &str,
    ) -> Option<Duration> {
        let policy = policy?;
        if let Some(timeout_secs) = policy
            .provider_timeouts
            .as_deref()
            .and_then(Self::parse_provider_timeout_overrides)
            .and_then(|timeouts| timeouts.get(provider_name).copied())
        {
            return Some(Duration::from_secs(timeout_secs));
        }
        policy.timeout_secs.map(Duration::from_secs)
    }

