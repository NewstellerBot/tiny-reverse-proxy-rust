    fn parse_allowed_models(raw: &str) -> Vec<String> {
        parse_string_array(raw)
    }

    fn visible_models_for_key(&self, record: &VirtualKeyRecord) -> Vec<(String, String)> {
        let mut models = self.all_models();
        if let Some(ref allowed) = record.allowed_models {
            let allowed = Self::parse_allowed_models(allowed);
            models.retain(|(model, _)| allowed.iter().any(|candidate| candidate == model));
        }
        models
    }

    /// Build an OpenAI-compatible /v1/models response listing all available models.
    fn handle_list_models(
        &self,
        record: &VirtualKeyRecord,
    ) -> Response<http_body_util::combinators::BoxBody<Bytes, hyper::Error>> {
        let models = self.visible_models_for_key(record);
        let entries: Vec<String> = models
            .iter()
            .map(|(model, owner)| {
                format!(
                    r#"{{"id":"{}","object":"model","created":0,"owned_by":"{}"}}"#,
                    model, owner,
                )
            })
            .collect();

        let body = format!(r#"{{"object":"list","data":[{}]}}"#, entries.join(","),);

        let mut resp = Response::builder()
            .status(StatusCode::OK)
            .body(
                Full::new(Bytes::from(body))
                    .map_err(|never| match never {})
                    .boxed(),
            )
            .unwrap();
        resp.headers_mut()
            .insert("content-type", HeaderValue::from_static("application/json"));
        resp
    }

    /// Build an OpenAI-compatible /v1/models/{model} response for a single model.
    fn handle_retrieve_model(
        &self,
        record: &VirtualKeyRecord,
        model_id: &str,
    ) -> Response<http_body_util::combinators::BoxBody<Bytes, hyper::Error>> {
        let provider_names = self.model_to_provider.get(model_id);
        match provider_names {
            Some(owners) => {
                if let Some(ref allowed) = record.allowed_models {
                    let allowed = Self::parse_allowed_models(allowed);
                    if !allowed.iter().any(|candidate| candidate == model_id) {
                        return json_error_response(
                            StatusCode::NOT_FOUND,
                            &format!("The model '{}' does not exist", model_id),
                            "invalid_request_error",
                            "model_not_found",
                        );
                    }
                }
                let owner = owners.first().map(|s| s.as_str()).unwrap_or("unknown");
                let body = format!(
                    r#"{{"id":"{}","object":"model","created":0,"owned_by":"{}"}}"#,
                    model_id, owner,
                );
                let mut resp = Response::builder()
                    .status(StatusCode::OK)
                    .body(
                        Full::new(Bytes::from(body))
                            .map_err(|never| match never {})
                            .boxed(),
                    )
                    .unwrap();
                resp.headers_mut()
                    .insert("content-type", HeaderValue::from_static("application/json"));
                resp
            }
            None => json_error_response(
                StatusCode::NOT_FOUND,
                &format!("The model '{}' does not exist", model_id),
                "invalid_request_error",
                "model_not_found",
            ),
        }
    }
